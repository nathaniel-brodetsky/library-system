#pragma once

#include <string>

struct Дата {
    int рік;
    int місяць;
    int день;
};

inline int вДні(Дата дата) {
    return дата.рік * 365 + дата.місяць * 30 + дата.день;
}

class Читач {
public:
    int id_читача;
    std::string ПІБ;
    std::string email;

    Читач() {
        id_читача = 0;
    }

    Читач(int id, std::string піб, std::string пошта) {
        id_читача = id;
        ПІБ = піб;
        email = пошта;
    }

    int отриматиID() {
        return id_читача;
    }
};

class Книга {
public:
    std::string ISBN;
    std::string назва;
    std::string автор;

    Книга() {}

    Книга(std::string isbn, std::string назваКниги, std::string авторКниги) {
        ISBN = isbn;
        назва = назваКниги;
        автор = авторКниги;
    }

    std::string отриматиISBN() {
        return ISBN;
    }
};

class ПримірникКниги {
public:
    int інвентарний_номер;
    std::string ISBN;
    std::string статус;

    ПримірникКниги() {
        інвентарний_номер = 0;
        статус = "відсутній";
    }

    ПримірникКниги(int номер) {
        інвентарний_номер = номер;
        статус = "доступний";
    }

    int отриматиІнвНомер() {
        return інвентарний_номер;
    }

    std::string отриматиСтатус() {
        return статус;
    }

    void встановитиСтатус(std::string новийСтатус) {
        статус = новийСтатус;
    }
};

class Транзакція {
public:
    int id_транзакції;
    int id_читача;
    int інв_номер;
    Дата дата_видачі;
    Дата дата_повернення_очікувана;
    std::string статус;

    Транзакція(int id, int читач, int номер, Дата видача, Дата повернення) {
        id_транзакції = id;
        id_читача = читач;
        інв_номер = номер;
        дата_видачі = видача;
        дата_повернення_очікувана = повернення;
        статус = "активна";
    }

    int отриматиІнвНомер() {
        return інв_номер;
    }
};