#pragma once

#include <vector>

#include "library_entities.h"

class РеєстрЧитачів {
public:
    std::vector<Читач> списокЧитачів;

    bool додатиЧитача(Читач читач) {
        списокЧитачів.push_back(читач);
        return true;
    }

    Читач знайтиЧитача(int id) {
        for (int i = 0; i < (int)списокЧитачів.size(); i++) {
            if (списокЧитачів[i].отриматиID() == id) {
                return списокЧитачів[i];
            }
        }
        return Читач();
    }
};

class РеєстрПримірників {
public:
    std::vector<ПримірникКниги> списокПримірників;

    bool додатиПримірник(ПримірникКниги примірник) {
        списокПримірників.push_back(примірник);
        return true;
    }

    ПримірникКниги знайтиПримірник(int id) {
        for (int i = 0; i < (int)списокПримірників.size(); i++) {
            if (списокПримірників[i].отриматиІнвНомер() == id) {
                return списокПримірників[i];
            }
        }
        return ПримірникКниги();
    }
};

class РеєстрТранзакцій {
public:
    std::vector<Транзакція> списокТранзакцій;
    int next_id = 1;

    bool записатиТранзакцію(Транзакція тр) {
        Транзакція новаТр = тр;
        новаТр.id_транзакції = next_id++;
        списокТранзакцій.push_back(новаТр);
        return true;
    }

    std::vector<Транзакція> знайтиАктивніТранзакції(int id_читача) {
        std::vector<Транзакція> активніТранзакції;
        for (int i = 0; i < (int)списокТранзакцій.size(); i++) {
            if (списокТранзакцій[i].id_читача == id_читача) {
                if (списокТранзакцій[i].статус == "активна") {
                    активніТранзакції.push_back(списокТранзакцій[i]);
                } else if (списокТранзакцій[i].статус == "повернена") {
                }
            }
        }
        return активніТранзакції;
    }
};