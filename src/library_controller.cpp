#include "library_controller.h"

#include <iostream>

std::string БібліотечнийКонтролер::видатиКнигу(int idЧитача, int інвНомер, Дата дата) {
    Читач поточнийЧитач = реєстрЧитачів.знайтиЧитача(idЧитача);
    if (поточнийЧитач.отриматиID() == 0) {
        std::cout << "Помилка: читач не зареєстрований" << std::endl;
        return "Читач не зареєстрований";
    }

    std::vector<Транзакція> активні = реєстрТранзакцій.знайтиАктивніТранзакції(idЧитача);
    for (int i = 0; i < (int)активні.size(); i++) {
        if (вДні(дата) > вДні(активні[i].дата_повернення_очікувана)) {
            std::cout << "Помилка: читач має заборгованість" << std::endl;
            return "Заборгованість";
        }
    }

    if (активні.size() >= 3) {
        std::cout << "Помилка: перевищено ліміт" << std::endl;
        return "Ліміт";
    }

    ПримірникКниги поточнийПримірник = реєстрПримірників.знайтиПримірник(інвНомер);
    if (поточнийПримірник.отриматиСтатус() != "доступний") {
        std::cout << "Помилка: примірник недоступний" << std::endl;
        return "Недоступний";
    }

    Дата очікуванеПовернення = дата;
    очікуванеПовернення.день = очікуванеПовернення.день + 14;

    Транзакція новаТранзакція(0, поточнийЧитач.отриматиID(), поточнийПримірник.отриматиІнвНомер(), дата,
                              очікуванеПовернення);
    bool збережено = реєстрТранзакцій.записатиТранзакцію(новаТранзакція);
    if (збережено) {
        поточнийПримірник.встановитиСтатус("виданий");
        std::cout << "Книгу видано" << std::endl;
        return "OK";
    }
    return "Помилка";
}